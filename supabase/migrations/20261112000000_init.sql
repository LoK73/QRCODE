-- Schema della piattaforma multi-cliente.
--
-- Chi legge e scrive cosa:
--   * il bot (worker) si collega con la stringa di connessione diretta e vede tutto;
--   * gli utenti della dashboard passano da Supabase Auth: le regole RLS qui sotto
--     fanno vedere a ciascuno solo i propri clienti;
--   * la dashboard non modifica mai le commesse: chiede un'azione (tabella "azioni")
--     che il bot esegue e di cui scrive l'esito, anche nel gruppo WhatsApp.

create type public.ruolo as enum ('admin_agenzia', 'operatore_agenzia', 'responsabile_cliente', 'lettore_cliente');

-- ---------------------------------------------------------------- clienti

create table public.clients (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  sector text not null default '',
  status text not null default 'attivo' check (status in ('attivo', 'sospeso')),
  -- Scheda per l'AI: chi è il cliente, parole ricorrenti, campi personalizzati, regole.
  profile text not null default '',
  trigger_prefix text not null default '',
  proposal_ttl_hours integer not null default 24 check (proposal_ttl_hours > 0),
  -- Chi può approvare: 'cliente' = i responsabili del cliente (anche da WhatsApp) o l'agenzia;
  -- 'agenzia' = solo l'agenzia, dalla dashboard.
  approval_rule text not null default 'cliente' check (approval_rule in ('cliente', 'agenzia')),
  monthly_budget_usd numeric(10, 2) not null default 0 check (monthly_budget_usd >= 0),
  show_costs_to_client boolean not null default false,
  prefilter boolean not null default false,
  timezone text not null default 'Europe/Rome',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.client_sites (
  client_id uuid primary key references public.clients (id) on delete cascade,
  url text not null,
  wp_user text not null,
  post_types text[] not null default '{post,page}',
  woocommerce boolean not null default false,
  verify_public boolean not null default true,
  -- Esito dell'ultimo "Prova connessione" (vedi SiteCheck nel bot).
  last_check jsonb,
  last_check_at timestamptz,
  updated_at timestamptz not null default now()
);

-- Password applicazione di WordPress, cifrata dal server con CREDENTIALS_KEY.
-- Nessuna regola RLS: gli utenti della dashboard non possono leggerla in nessun caso.
create table public.client_secrets (
  client_id uuid primary key references public.clients (id) on delete cascade,
  wp_app_password_enc text not null,
  updated_at timestamptz not null default now()
);

-- Chat WhatsApp collegate a un cliente: gruppi (chat_id = group_id) o chat private (chat_id = numero).
create table public.client_channels (
  id uuid primary key default gen_random_uuid(),
  client_id uuid not null references public.clients (id) on delete cascade,
  chat_id text not null unique,
  chat_type text not null default 'group' check (chat_type in ('group', 'individual')),
  name text not null default '',
  active boolean not null default true,
  created_at timestamptz not null default now()
);
create index client_channels_client on public.client_channels (client_id);

-- Persone del cliente su WhatsApp; can_approve = può dare l'ok dal gruppo.
create table public.contacts (
  id uuid primary key default gen_random_uuid(),
  client_id uuid not null references public.clients (id) on delete cascade,
  wa_id text not null,
  name text not null default '',
  can_approve boolean not null default false,
  unique (client_id, wa_id)
);

-- ---------------------------------------------------------------- utenti della dashboard

create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  full_name text not null default '',
  email text not null default ''
);

-- client_id vuoto = ruolo d'agenzia valido per tutti i clienti.
create table public.memberships (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users (id) on delete cascade,
  client_id uuid references public.clients (id) on delete cascade,
  role public.ruolo not null,
  created_at timestamptz not null default now(),
  check ((role in ('admin_agenzia')) = false or client_id is null),
  check ((role in ('responsabile_cliente', 'lettore_cliente')) = false or client_id is not null)
);
create unique index memberships_unique on public.memberships (user_id, coalesce(client_id, '00000000-0000-0000-0000-000000000000'::uuid));

-- ---------------------------------------------------------------- lavoro del bot

create table public.commesse (
  id bigint generated by default as identity primary key,
  client_id uuid not null references public.clients (id) on delete cascade,
  chat_id text not null,
  chat_type text not null check (chat_type in ('group', 'individual')),
  requester_id text not null,
  requester_name text,
  original_text text not null,
  summary text not null,
  details jsonb not null default '[]',
  operations jsonb not null,
  -- Anteprima prima/dopo calcolata dal bot al momento della proposta.
  preview jsonb not null default '[]',
  -- true se è una modifica approvabile a colpo d'occhio dall'elenco.
  small boolean not null default false,
  status text not null check (status in ('in_attesa', 'programmata', 'in_corso', 'completata', 'in_ripristino', 'errore', 'annullata', 'ripristinata', 'scaduta')),
  approved_by text,
  result_urls jsonb not null default '[]',
  undo jsonb not null default '[]',
  error text,
  source_message_id text,
  proposal_message_id text,
  apply_at timestamptz,
  revert_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index commesse_client_status on public.commesse (client_id, status, id desc);
create index commesse_chat_status on public.commesse (chat_id, status);
create index commesse_source on public.commesse (source_message_id);
create index commesse_proposal on public.commesse (proposal_message_id);

create table public.messaggi (
  id bigint generated by default as identity primary key,
  client_id uuid references public.clients (id) on delete cascade,
  chat_id text not null,
  sender text not null,
  sender_name text,
  text text not null,
  bot boolean not null default false,
  ts bigint not null,
  message_id text,
  media jsonb,
  media_used boolean not null default false
);
create index messaggi_chat on public.messaggi (chat_id, id);
create unique index messaggi_message_id on public.messaggi (message_id) where message_id is not null;

-- Coda dei messaggi WhatsApp in arrivo (solo per il bot).
create table public.inbox (
  message_id text primary key,
  chat_id text not null,
  payload jsonb not null,
  status text not null default 'pending' check (status in ('pending', 'processing', 'done', 'failed')),
  attempts integer not null default 0,
  error text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index inbox_status on public.inbox (status);

create table public.consumi_ai (
  id bigint generated by default as identity primary key,
  client_id uuid references public.clients (id) on delete cascade,
  chat_id text not null,
  commessa_id bigint references public.commesse (id) on delete set null,
  model text not null,
  purpose text not null,
  calls integer not null,
  input_tokens integer not null,
  output_tokens integer not null,
  cache_read_tokens integer not null,
  cache_write_tokens integer not null,
  cost_usd numeric(12, 6),
  created_at timestamptz not null default now()
);
create index consumi_ai_client on public.consumi_ai (client_id, created_at);
create index consumi_ai_chat on public.consumi_ai (chat_id, created_at);

-- Azioni chieste dalla dashboard, eseguite dal bot.
create table public.azioni (
  id bigint generated by default as identity primary key,
  client_id uuid not null references public.clients (id) on delete cascade,
  commessa_id bigint references public.commesse (id) on delete cascade,
  tipo text not null check (tipo in ('approva', 'annulla', 'ripristina', 'ripristina_forza', 'riprova', 'prova_sito')),
  richiesta_da uuid references auth.users (id) on delete set null default auth.uid(),
  stato text not null default 'in_coda' check (stato in ('in_coda', 'in_corso', 'fatta', 'fallita')),
  esito text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check ((tipo = 'prova_sito') = (commessa_id is null))
);
create index azioni_coda on public.azioni (stato, id);
create index azioni_commessa on public.azioni (commessa_id);

-- ---------------------------------------------------------------- funzioni per i permessi

create function public.is_agency() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from memberships
    where user_id = auth.uid() and client_id is null and role in ('admin_agenzia', 'operatore_agenzia')
  );
$$;

create function public.is_agency_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from memberships where user_id = auth.uid() and client_id is null and role = 'admin_agenzia'
  );
$$;

-- Può vedere i dati del cliente: tutta l'agenzia, oppure chi ha un ruolo su quel cliente.
create function public.can_see_client(cid uuid) returns boolean
language sql stable security definer set search_path = public as $$
  select public.is_agency() or exists (
    select 1 from memberships where user_id = auth.uid() and client_id = cid
  );
$$;

-- Può gestire le impostazioni del cliente: l'agenzia, o un operatore assegnato a quel cliente.
create function public.can_manage_client(cid uuid) returns boolean
language sql stable security definer set search_path = public as $$
  select public.is_agency() or exists (
    select 1 from memberships where user_id = auth.uid() and client_id = cid and role = 'operatore_agenzia'
  );
$$;

-- Può approvare, annullare e ripristinare le commesse del cliente.
create function public.can_decide_client(cid uuid) returns boolean
language sql stable security definer set search_path = public as $$
  select public.can_manage_client(cid) or exists (
    select 1
    from memberships m join clients c on c.id = m.client_id
    where m.user_id = auth.uid() and m.client_id = cid
      and m.role = 'responsabile_cliente' and c.approval_rule = 'cliente'
  );
$$;

-- ---------------------------------------------------------------- regole RLS

alter table public.clients enable row level security;
alter table public.client_sites enable row level security;
alter table public.client_secrets enable row level security;
alter table public.client_channels enable row level security;
alter table public.contacts enable row level security;
alter table public.profiles enable row level security;
alter table public.memberships enable row level security;
alter table public.commesse enable row level security;
alter table public.messaggi enable row level security;
alter table public.inbox enable row level security;
alter table public.consumi_ai enable row level security;
alter table public.azioni enable row level security;

create policy clients_select on public.clients for select to authenticated using (public.can_see_client(id));
create policy clients_insert on public.clients for insert to authenticated with check (public.is_agency());
create policy clients_update on public.clients for update to authenticated using (public.can_manage_client(id)) with check (public.can_manage_client(id));
create policy clients_delete on public.clients for delete to authenticated using (public.is_agency_admin());

create policy sites_select on public.client_sites for select to authenticated using (public.can_manage_client(client_id));
create policy sites_write on public.client_sites for all to authenticated using (public.can_manage_client(client_id)) with check (public.can_manage_client(client_id));

create policy channels_select on public.client_channels for select to authenticated using (public.can_see_client(client_id));
create policy channels_write on public.client_channels for all to authenticated using (public.can_manage_client(client_id)) with check (public.can_manage_client(client_id));

create policy contacts_select on public.contacts for select to authenticated using (public.can_see_client(client_id));
create policy contacts_write on public.contacts for all to authenticated using (public.can_manage_client(client_id)) with check (public.can_manage_client(client_id));

create policy profiles_select on public.profiles for select to authenticated using (id = auth.uid() or public.is_agency());
create policy profiles_update on public.profiles for update to authenticated using (id = auth.uid()) with check (id = auth.uid());
create policy profiles_insert on public.profiles for insert to authenticated with check (id = auth.uid());

create policy memberships_select on public.memberships for select to authenticated using (user_id = auth.uid() or public.is_agency());
create policy memberships_write on public.memberships for all to authenticated using (public.is_agency_admin()) with check (public.is_agency_admin());

-- Commesse, messaggi e consumi: sola lettura per gli utenti; li scrive solo il bot.
create policy commesse_select on public.commesse for select to authenticated using (public.can_see_client(client_id));
create policy messaggi_select on public.messaggi for select to authenticated using (client_id is not null and public.can_see_client(client_id));
create policy consumi_select on public.consumi_ai for select to authenticated using (
  client_id is not null and (
    public.is_agency()
    or (public.can_see_client(client_id) and exists (select 1 from public.clients c where c.id = client_id and c.show_costs_to_client))
  )
);

create policy azioni_select on public.azioni for select to authenticated using (public.can_see_client(client_id));
create policy azioni_insert on public.azioni for insert to authenticated with check (
  richiesta_da = auth.uid()
  and stato = 'in_coda'
  and esito is null
  and (
    (tipo = 'prova_sito' and public.can_manage_client(client_id))
    or (
      tipo <> 'prova_sito'
      and public.can_decide_client(client_id)
      -- la commessa deve appartenere davvero a quel cliente
      and exists (select 1 from public.commesse k where k.id = commessa_id and k.client_id = azioni.client_id)
    )
  )
);

-- ---------------------------------------------------------------- privilegi

revoke all on all tables in schema public from anon;
grant select, insert, update, delete on all tables in schema public to authenticated;
revoke all on public.client_secrets, public.inbox from authenticated;
revoke insert, update, delete on public.commesse, public.messaggi, public.consumi_ai from authenticated;
revoke update, delete on public.azioni from authenticated;
grant usage, select on all sequences in schema public to authenticated;
grant all on all tables in schema public to service_role;
grant all on all sequences in schema public to service_role;
grant execute on function public.is_agency(), public.is_agency_admin(), public.can_see_client(uuid), public.can_manage_client(uuid), public.can_decide_client(uuid) to authenticated;

-- Crea il profilo quando nasce un utente (nome ed email da Supabase Auth).
create function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, full_name, email)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'full_name', ''), coalesce(new.email, ''))
  on conflict (id) do nothing;
  return new;
end;
$$;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

